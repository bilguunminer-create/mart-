update public.store_settings s
set data = jsonb_set(s.data, '{products}', (
      select jsonb_agg(
        case when f.features is not null and (case when jsonb_typeof(p->'features') = 'array' then jsonb_array_length(p->'features') else 0 end) = 0
             then jsonb_set(p, '{features}', f.features)
             else p end
        order by t.ord)
      from jsonb_array_elements(s.data->'products') with ordinality as t(p, ord)
      left join f on f.id = t.p->>'id'
    )),
    version = s.version + 1,
    updated_at = now()
